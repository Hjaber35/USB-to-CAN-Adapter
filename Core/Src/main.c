HAL_StatusTypeDef CAN_ApplyFilters(void)
{
    FDCAN_FilterTypeDef canFilter = {0};

    canFilter.IdType = FDCAN_STANDARD_ID;
    canFilter.FilterIndex = 0;
    canFilter.FilterType = FDCAN_FILTER_RANGE;
    canFilter.FilterConfig = FDCAN_FILTER_TO_RXFIFO0;
    canFilter.FilterID1 = 0x000;
    canFilter.FilterID2 = 0x7FF;

    if (HAL_FDCAN_ConfigFilter(&hfdcan1, &canFilter) != HAL_OK)
    {
        return HAL_ERROR;
    }

    if (HAL_FDCAN_ConfigGlobalFilter(
            &hfdcan1,
            FDCAN_ACCEPT_IN_RX_FIFO0,
            FDCAN_ACCEPT_IN_RX_FIFO0,
            FDCAN_REJECT_REMOTE,
            FDCAN_REJECT_REMOTE) != HAL_OK)
    {
        return HAL_ERROR;
    }

    return HAL_OK;
}

